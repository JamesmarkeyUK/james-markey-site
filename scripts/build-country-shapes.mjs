// Generates src/data/countryShapes.ts — projected SVG path data for every
// country, used by the WorldMap to render the dotted-geography base layer.
//
// Source: Natural Earth 1:110m Admin-0 countries (public domain), via the
// natural-earth-vector mirror. Run with:  node scripts/build-country-shapes.mjs
//
// The projection matches WorldMap.astro exactly (equirectangular into a
// 1000x500 viewBox), so paths line up with the centroid pins.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SRC =
  'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_admin_0_countries.geojson';
const VIEW_W = 1000;
const VIEW_H = 500;
const PRECISION = 1; // decimal places for projected coords

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(__dirname, '..', 'src', 'data', 'countryShapes.ts');

const project = (lon, lat) => [
  +(((lon + 180) / 360) * VIEW_W).toFixed(PRECISION),
  +(((90 - lat) / 180) * VIEW_H).toFixed(PRECISION),
];

function geomToPath(geom) {
  const polys = geom.type === 'Polygon' ? [geom.coordinates] : geom.coordinates;
  let d = '';
  for (const poly of polys) {
    for (const ring of poly) {
      ring.forEach(([lon, lat], i) => {
        const [x, y] = project(lon, lat);
        d += (i === 0 ? 'M' : 'L') + x + ',' + y;
      });
      d += 'Z';
    }
  }
  return d;
}

const codeOf = (p) => {
  const c = p.ISO_A2_EH && p.ISO_A2_EH !== '-99' ? p.ISO_A2_EH : p.ISO_A2;
  return c && c !== '-99' ? c : null;
};

const res = await fetch(SRC);
if (!res.ok) throw new Error(`Failed to fetch source GeoJSON: ${res.status}`);
const geo = await res.json();

const shapes = [];
for (const f of geo.features) {
  const code = codeOf(f.properties);
  if (!code) continue;
  shapes.push({ code, d: geomToPath(f.geometry) });
}
shapes.sort((a, b) => a.code.localeCompare(b.code));

const body = shapes.map((s) => `  { code: '${s.code}', d: '${s.d}' },`).join('\n');
const out = `// AUTO-GENERATED by scripts/build-country-shapes.mjs — do not edit by hand.
// Natural Earth 1:110m Admin-0 countries (public domain), projected
// equirectangular into the WorldMap's 1000x500 viewBox.

export type CountryShape = { code: string; d: string };

export const countryShapes: CountryShape[] = [
${body}
];
`;

fs.writeFileSync(OUT, out);
console.log(`Wrote ${shapes.length} country shapes to ${OUT} (${(out.length / 1024).toFixed(0)} KB)`);
